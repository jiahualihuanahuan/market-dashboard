const COMPANY_STOP =
  /\b(inc|incorporated|corp|corporation|co|ltd|limited|plc|sa|nv|ag|the|class|cls|ordinary|common|shs|shares|sv|company|holdings|group|plc)\b/gi;

export function normalizeCompanyName(name: string): string {
  return name
    .toLowerCase()
    .replace(/&/g, "&")
    .replace(/&/g, " ")
    .replace(/[^a-z0-9]+/g, " ")
    .replace(COMPANY_STOP, " ")
    .replace(/\bof\b/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

