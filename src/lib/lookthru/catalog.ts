const COMPANY_TICKERS = new Map<string, string[]>();

function indexCompany(name: string, symbol: string) {
  const n = normalizeCompanyName(name);
  if (!n || n.length < 3 || isSynthetic(symbol)) return;
  const list = COMPANY_TICKERS.get(n) ?? [];
  if (!list.includes(symbol)) list.push(symbol);
  COMPANY_TICKERS.set(n, list);
}

for (const inst of FUNDS) {
  indexCompany(inst.name, inst.symbol);
  for (const h of inst.holdings ?? []) indexCompany(h.name, h.symbol);
}

function pickByGeo(hits: string[], geo?: string): string {
  const g = (geo ?? "").toLowerCase();
  const canada = g.includes("canada");
  const us = /united states|u\.s\.|usa/.test(g);
  if (canada) {
    const tsx = hits.find((h) => /\.(TO|NE|V)$/i.test(h));
    if (tsx) return tsx;
  }
  if (us) {
    const usa = hits.find((h) => h.endsWith(".US") || !/\.(TO|NE|V)$/i.test(h));
    if (usa) return usa;
  }
  return hits[0] ?? "";
}

export function tickerFromCompanyName(name: string, geo?: string): string | null {
  const n = normalizeCompanyName(name);
  if (!n) return null;
  if (/^(cash|cash other|other assets|net other|cash leverage)/.test(n)) return "CASH";
  const extra = EXTRA_COMPANY_TICKERS[n];
  if (extra) return applyAlias(extra);
  for (const [key, ticker] of Object.entries(EXTRA_COMPANY_TICKERS)) {
    if (key.length >= 5 && (n === key || n.startsWith(`${key} `))) return applyAlias(ticker);
  }
  const hits = COMPANY_TICKERS.get(n);
  if (hits?.length) {
    const picked = pickByGeo(hits, geo);
    return picked ? applyAlias(picked) : null;
  }
  return null;
}