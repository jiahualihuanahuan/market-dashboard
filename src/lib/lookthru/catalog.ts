export function catalogInstrument(ticker: string): Instrument | undefined {
  const aliased = applyAlias(ticker);
  const direct = BY_SYMBOL.get(aliased) ?? BY_ISSUER.get(issuerKey(aliased));
  if (direct) return direct;
  const base = stripShareClass(aliased);
  if (base && base !== issuerKey(aliased)) {
    return BY_ISSUER.get(base) ?? BY_SYMBOL.get(`${base}.TO`) ?? BY_SYMBOL.get(`${base}.NE`);
  }
  return undefined;
}

export function isSynthetic(symbol: string): boolean {
  const s = issuerKey(symbol);
  return s === "CASH" || s === "OPTIONS" || s === "OTHER";
}

export function syntheticInstrument(symbol: string): Instrument {
  const key = issuerKey(symbol);
  const name =
    key === "CASH"
      ? "Cash, leverage & other"
      : key === "OPTIONS"
        ? "Options overlay"
        : "Other holdings";
  return {
    symbol: key,
    displaySymbol: key,
    name,
    kind: key === "CASH" ? "cash" : "other",
    currency: "CAD",
    price: key === "CASH" ? 1 : null,
    changePct: null,
    holdings: null,
    sectors: [{ name: key === "CASH" ? "Cash" : "Other", weight: 1 }],
    source: "synthetic",
    coverage: 1,
  };
}

